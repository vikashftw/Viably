import { Octokit } from '@octokit/rest';
import { generateScaffold } from './scaffold-generator.js';

// Lazy initialization to ensure dotenv has loaded
let octokit = null;
function getOctokit() {
  if (!octokit) {
    octokit = new Octokit({
      auth: process.env.GITHUB_TOKEN
    });
  }
  return octokit;
}

export async function createPullRequest(targetRepo, implementation, assignments, viablyAnalysis) {
  const octokit = getOctokit();
  const { owner, repo, branch: baseBranch } = targetRepo;
  const featureBranch = `feature/${sanitizeBranchName(viablyAnalysis.feature_name)}`;

  console.log(`[GitHub] Creating PR in ${owner}/${repo}`);

  // DEBUG LOG
  console.log('[DEBUG] Attempting to get ref with:', {
    owner,
    repo,
    baseBranch,
    tokenExists: !!process.env.GITHUB_TOKEN,
    tokenLast4: process.env.GITHUB_TOKEN ? process.env.GITHUB_TOKEN.slice(-4) : 'N/A'
  });

  try {
    // Get base branch SHA
    const { data: refData } = await octokit.git.getRef({
      owner,
      repo,
      ref: `heads/${baseBranch}`
    });
    const baseSha = refData.object.sha;

    // Create or update feature branch
    try {
      await octokit.git.createRef({
        owner,
        repo,
        ref: `refs/heads/${featureBranch}`,
        sha: baseSha
      });
    } catch (error) {
      if (error.status === 422) {
        await octokit.git.updateRef({
          owner,
          repo,
          ref: `heads/${featureBranch}`,
          sha: baseSha,
          force: true
        });
      } else {
        throw error;
      }
    }

    // Get base tree
    const { data: baseCommit } = await octokit.git.getCommit({
      owner,
      repo,
      commit_sha: baseSha
    });

    // Create file blobs
    const fileBlobs = await Promise.all(
      implementation.file_structure.map(async (file) => {
        const content = generateScaffold(file, viablyAnalysis);
        const { data: blob } = await octokit.git.createBlob({
          owner,
          repo,
          content: Buffer.from(content).toString('base64'),
          encoding: 'base64'
        });
        return {
          path: file.path,
          mode: '100644',
          type: 'blob',
          sha: blob.sha
        };
      })
    );

    // Create tree and commit
    const { data: newTree } = await octokit.git.createTree({
      owner,
      repo,
      base_tree: baseCommit.tree.sha,
      tree: fileBlobs
    });

    const { data: newCommit } = await octokit.git.createCommit({
      owner,
      repo,
      message: `feat: ${viablyAnalysis.feature_name}\n\nGenerated by Viably AI`,
      tree: newTree.sha,
      parents: [baseSha]
    });

    // Update branch
    await octokit.git.updateRef({
      owner,
      repo,
      ref: `heads/${featureBranch}`,
      sha: newCommit.sha
    });

    // Create PR
    const prBody = implementation.pr_description || `# ${viablyAnalysis.feature_name}\n\nGenerated by Viably AI`;
    const { data: pr } = await octokit.pulls.create({
      owner,
      repo,
      title: `[Viably AI] ${viablyAnalysis.feature_name}`,
      head: featureBranch,
      base: baseBranch,
      body: prBody
    });

    // Add labels
    const labels = generateLabels(viablyAnalysis);
    if (labels.length > 0) {
      try {
        await octokit.issues.addLabels({
          owner,
          repo,
          issue_number: pr.number,
          labels
        });
      } catch (error) {
        console.warn('[GitHub] Failed to add labels:', error.message);
      }
    }

    console.log(`[GitHub] PR created successfully: ${pr.html_url}`);

    return {
      url: pr.html_url,
      number: pr.number,
      branch: featureBranch,
      status: 'created',
      labels,
      files_created: implementation.file_structure.length
    };

  } catch (error) {
    console.error('[GitHub] PR creation error:', error.message);
    throw new Error(`GitHub PR creation failed: ${error.message}`);
  }
}

function sanitizeBranchName(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').substring(0, 50);
}

function generateLabels(viablyAnalysis) {
  const labels = ['viably-ai'];

  const skills = viablyAnalysis.upskilling_insights?.bottleneck_skills || [];
  skills.forEach(skill => labels.push(skill.toLowerCase()));

  const riskLevel = viablyAnalysis.competitor_analysis?.competitive_risk_level;
  if (riskLevel) labels.push(`risk-${riskLevel.toLowerCase()}`);

  const cost = viablyAnalysis.engineer_analysis?.estimated_cost_usd || 0;
  if (cost > 1000000) labels.push('high-cost');
  else if (cost > 500000) labels.push('medium-cost');
  else labels.push('low-cost');

  return [...new Set(labels)].slice(0, 10);
}
